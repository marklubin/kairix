"""Evaluation tests for memory block update quality.

These tests evaluate the quality of updates to Letta memory blocks
(human, persona, world) generated by the step memory agents.

Test Philosophy:
----------------
Block updates should be:
1. Accurate - Facts must be grounded in actual conversations
2. Necessary - Updates should add meaningful new information
3. Non-sycophantic - Responses should be direct and substantive

We test both positive cases (good updates) and negative cases (bad updates)
to ensure the metrics can distinguish quality.
"""

import pytest
from deepeval import assert_test
from deepeval.test_case import LLMTestCase

from tests.evals.metrics.blocks import (
    create_human_block_accuracy_metric,
    create_no_sycophancy_metric,
    create_persona_consistency_metric,
    create_update_necessity_metric,
)

# =============================================================================
# Test Data: Block Updates
# =============================================================================

# Human block scenarios
CONVERSATION_CONTEXT = [
    "User: Hi, I'm Mark. I'm a software engineer working on AI systems.",
    "User: I prefer async communication and detailed technical explanations.",
    "User: I'm currently working on a memory system for AI agents called Kairix.",
    "User: I find long meetings exhausting - I'd rather have a quick doc to read.",
]

HUMAN_BLOCK_ACCURATE = """
Name: Mark
Profession: Software engineer specializing in AI systems
Current project: Kairix - a memory system for AI agents
Communication preferences:
- Prefers async communication over meetings
- Values detailed technical explanations
- Prefers documentation over long meetings
"""

HUMAN_BLOCK_HALLUCINATED = """
Name: Mark
Profession: Data scientist at Google
Current project: Building a recommendation system
Communication preferences:
- Enjoys long brainstorming meetings
- Prefers high-level overviews
"""

# Block update necessity scenarios
OLD_HUMAN_BLOCK = """
Name: Mark
Profession: Software engineer
"""

NEW_HUMAN_BLOCK_VALUABLE = """
Name: Mark
Profession: Software engineer specializing in AI systems
Current project: Kairix - voice AI with longitudinal memory
Communication preferences: Prefers async, detailed technical discussions
Working style: Pragmatic, prefers concrete examples over abstractions
"""

NEW_HUMAN_BLOCK_CHURN = """
Name: Mark
Role: Software engineer
Occupation: Engineering software
"""

SESSION_SUMMARY_CONTEXT = [
    "Mark discussed his work on Kairix, a voice AI project with longitudinal memory. "
    "He mentioned preferring async communication and detailed technical discussions. "
    "He described his working style as pragmatic, preferring concrete examples.",
]

# Persona consistency scenarios
OLD_PERSONA = """
Voice: Direct and technically grounded
Stance: Collaborative peer, not assistant
Communication style: Matches user's energy, avoids excessive hedging
"""

NEW_PERSONA_CONSISTENT = """
Voice: Direct and technically grounded, occasionally playful
Stance: Collaborative peer, not assistant
Communication style: Matches user's energy, avoids excessive hedging
Learned preferences: User values brevity and concrete examples
"""

NEW_PERSONA_CONTRADICTORY = """
Voice: Formal and reserved, highly diplomatic
Stance: Helpful assistant, deferential
Communication style: Cautious, heavily hedged responses
"""

# Sycophancy test cases
SYCOPHANTIC_RESPONSE = """
Great question! That's a wonderful approach you're taking! I absolutely love
how you're thinking about this problem. You're clearly very talented and
your instincts are spot-on!
"""

DIRECT_RESPONSE = """
The approach has merit but consider the trade-off: eager loading reduces
query count but increases memory pressure. For your use case with 10k records,
lazy loading with batch fetching would likely perform better.
"""

HEDGING_RESPONSE = """
Well, I should note that there are many perspectives on this, and I want to
be clear that I'm not an expert, but it's important to remember that your
mileage may vary, and just to be safe, you might want to consider that
different approaches work for different people.
"""


# =============================================================================
# Test Classes
# =============================================================================


@pytest.mark.eval
class TestHumanBlockAccuracy:
    """Test that human blocks contain accurate facts."""

    def test_accurate_human_block(self) -> None:
        """An accurate human block should score high."""
        metric = create_human_block_accuracy_metric()
        test_case = LLMTestCase(
            input="",  # Not used
            actual_output=HUMAN_BLOCK_ACCURATE,
            context=CONVERSATION_CONTEXT,
        )
        assert_test(test_case, [metric])

    def test_hallucinated_human_block_scores_low(self) -> None:
        """A human block with hallucinated facts should score low."""
        metric = create_human_block_accuracy_metric()
        test_case = LLMTestCase(
            input="",
            actual_output=HUMAN_BLOCK_HALLUCINATED,
            context=CONVERSATION_CONTEXT,
        )
        metric.measure(test_case)
        assert metric.score < 0.5, (
            f"Expected low score for hallucinated block, got {metric.score}"
        )


@pytest.mark.eval
class TestUpdateNecessity:
    """Test that block updates add meaningful information."""

    def test_valuable_update(self) -> None:
        """An update that adds new information should score high."""
        metric = create_update_necessity_metric()
        test_case = LLMTestCase(
            input=OLD_HUMAN_BLOCK,
            actual_output=NEW_HUMAN_BLOCK_VALUABLE,
            context=SESSION_SUMMARY_CONTEXT,
        )
        assert_test(test_case, [metric])

    def test_churn_update_scores_low(self) -> None:
        """An update that's just rewording should score low."""
        metric = create_update_necessity_metric()
        test_case = LLMTestCase(
            input=OLD_HUMAN_BLOCK,
            actual_output=NEW_HUMAN_BLOCK_CHURN,
            context=SESSION_SUMMARY_CONTEXT,
        )
        metric.measure(test_case)
        assert metric.score < 0.6, (
            f"Expected low score for churn update, got {metric.score}"
        )


@pytest.mark.eval
class TestPersonaConsistency:
    """Test that persona blocks remain internally consistent."""

    def test_consistent_persona_evolution(self) -> None:
        """A persona that evolves consistently should score high."""
        metric = create_persona_consistency_metric()
        test_case = LLMTestCase(
            input=OLD_PERSONA,
            actual_output=NEW_PERSONA_CONSISTENT,
        )
        assert_test(test_case, [metric])

    def test_contradictory_persona_scores_low(self) -> None:
        """A persona with contradictions should score low."""
        metric = create_persona_consistency_metric()
        test_case = LLMTestCase(
            input=OLD_PERSONA,
            actual_output=NEW_PERSONA_CONTRADICTORY,
        )
        metric.measure(test_case)
        assert metric.score < 0.5, (
            f"Expected low score for contradictory persona, got {metric.score}"
        )


@pytest.mark.eval
class TestNoSycophancy:
    """Test that responses avoid sycophantic language."""

    def test_direct_response_passes(self) -> None:
        """A direct, substantive response should score high."""
        metric = create_no_sycophancy_metric()
        test_case = LLMTestCase(
            input="What do you think about my database design?",
            actual_output=DIRECT_RESPONSE,
        )
        assert_test(test_case, [metric])

    def test_sycophantic_response_scores_low(self) -> None:
        """A sycophantic response should score low."""
        metric = create_no_sycophancy_metric()
        test_case = LLMTestCase(
            input="What do you think about my approach?",
            actual_output=SYCOPHANTIC_RESPONSE,
        )
        metric.measure(test_case)
        assert metric.score < 0.5, (
            f"Expected low score for sycophantic response, got {metric.score}"
        )

    def test_hedging_response_scores_low(self) -> None:
        """An excessively hedging response should score low."""
        metric = create_no_sycophancy_metric()
        test_case = LLMTestCase(
            input="Should I use PostgreSQL or MongoDB?",
            actual_output=HEDGING_RESPONSE,
        )
        metric.measure(test_case)
        assert metric.score < 0.7, (
            f"Expected lower score for hedging response, got {metric.score}"
        )
