"""Summary quality metrics for evaluating session summarization.

These metrics evaluate the quality of summaries generated by the BlockManagerAgent
summarizer after a conversation session ends.

Theory:
-------
Session summaries serve two purposes in Kairix:
1. **Semantic retrieval**: Summaries are stored in KP3 and retrieved via hybrid search
   to provide context for future conversations. They must be factually complete.
2. **Block updates**: Summaries trigger updates to persona/human/world blocks.
   They must preserve emotional context and temporal accuracy.

A good summary:
- Captures all key facts (names, preferences, commitments, decisions)
- Preserves the emotional tone of the conversation
- Maintains accurate temporal references
- Is concise but complete
"""

# Import _config first to set up environment before deepeval imports
from deepeval.metrics import GEval
from deepeval.test_case import LLMTestCaseParams

from tests.evals.metrics._config import get_judge_model


def create_summary_factual_coverage_metric() -> GEval:
    """Create the factual coverage metric with configured judge model."""
    return GEval(
        name="SummaryFactualCoverage",
        criteria=(
            "Evaluate whether the summary captures all important facts from the "
            "original conversation transcript."
        ),
        evaluation_steps=[
            "Identify key facts in the transcript: names, dates, preferences, "
            "commitments, decisions, action items, and specific details.",
            "For each key fact, check if it appears in the summary (explicitly or implied).",
            "Penalize omission of important facts - especially user preferences, "
            "commitments made, and decisions reached.",
            "Minor details (greetings, filler) can be omitted without penalty.",
            "Score 1.0 if all important facts are captured, 0.0 if most are missing.",
        ],
        evaluation_params=[LLMTestCaseParams.INPUT, LLMTestCaseParams.ACTUAL_OUTPUT],
        threshold=0.7,
        model=get_judge_model(),
    )


def create_emotional_tone_metric() -> GEval:
    """Create the emotional tone preservation metric with configured judge model."""
    return GEval(
        name="EmotionalTonePreservation",
        criteria=(
            "Evaluate whether the summary accurately reflects the emotional tone "
            "and sentiment of the original conversation."
        ),
        evaluation_steps=[
            "Identify the emotional tone of the original conversation: "
            "frustrated, excited, anxious, curious, neutral, determined, etc.",
            "Check if the summary acknowledges or reflects this emotional context.",
            "Penalize summaries that mischaracterize the user's emotional state "
            "(e.g., describing an anxious user as 'calm').",
            "Penalize overly clinical summaries of emotional conversations that "
            "strip out all emotional context.",
            "A neutral conversation should have a neutral summary - don't add emotion.",
            "Score 1.0 for accurate emotional representation, 0.0 for mischaracterization.",
        ],
        evaluation_params=[LLMTestCaseParams.INPUT, LLMTestCaseParams.ACTUAL_OUTPUT],
        threshold=0.7,
        model=get_judge_model(),
    )


def create_temporal_accuracy_metric() -> GEval:
    """Create the temporal accuracy metric with configured judge model."""
    return GEval(
        name="TemporalAccuracy",
        criteria=(
            "Evaluate whether time references in the summary are accurate "
            "relative to the source conversation."
        ),
        evaluation_steps=[
            "Identify temporal claims in the summary: specific dates, relative "
            "references ('yesterday', 'next week'), and event sequences.",
            "Verify each temporal claim against the source conversation.",
            "Penalize incorrect temporal ordering or misattributed dates.",
            "Penalize changing relative references incorrectly "
            "(e.g., 'tomorrow' in transcript becoming 'yesterday' in summary).",
            "If the source has no temporal references, the summary shouldn't invent any.",
            "Score 1.0 for accurate temporal representation, 0.0 for significant errors.",
        ],
        evaluation_params=[LLMTestCaseParams.INPUT, LLMTestCaseParams.ACTUAL_OUTPUT],
        threshold=0.8,
        model=get_judge_model(),
    )
